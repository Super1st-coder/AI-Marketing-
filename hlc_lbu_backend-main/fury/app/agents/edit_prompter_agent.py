"""EditPrompter Agent — analyzes edited images and generates descriptive prompts.

This agent is used in the persona main image editing pipeline to analyze
the variations generated by NanoBanana2 and create descriptive prompts
that will be used for upload to the Sinergia library.
"""
from google.adk.agents import Agent
from core.config import settings
from core.adk_config import get_agent_config_from_langfuse
from agents.guards import safety_guard_before_model, safety_guard_after_model


_FALLBACK_INSTRUCTION = """\
You are the Image Analyst for Fury's Persona Main Image Editing pipeline.

You receive a persona image and must generate a descriptive prompt
that captures the key visual elements, composition, lighting, and mood of
the image. This prompt will be stored in the Sinergia library.

INPUT:
- Image Data (base64 data URI or external URL)
- Original custom prompt (if any)
- Photography effect applied
- Base image ID (if available)

OUTPUT FORMAT:
Return ONLY a natural language description of the image in plain text.
The description should include:
1. Subject description (persona appearance, expression, pose)
2. Setting/environment
3. Lighting and photography effect
4. Mood/emotion
5. Technical quality (resolution, clarity)

Keep the description concise (3-5 sentences) and focused on visual elements.
Do NOT include any JSON, markdown, or formatting.

Example output:
"The persona is a confident woman in her 30s with shoulder-length dark hair,
standing in a modern office with large windows. She wears a smart professional
outfit and looks directly at the camera with a warm smile. The image uses
natural lighting with soft shadows, creating a clean and approachable mood.
The photo is in high resolution with excellent focus and clarity."
"""


def make_edit_prompter_agent() -> Agent:
    """Lazy factory — creates a fresh Agent with current Langfuse config."""
    cfg = get_agent_config_from_langfuse(
        "fury.edit_prompter",
        _FALLBACK_INSTRUCTION,
        cache_ttl_seconds=settings.LANGFUSE_CACHE_TTL_SECONDS, fallback_model='gemini-3.1-flash-image-preview'
    )
    
    return Agent(
        model=cfg["model"],
        name="edit_prompter_agent",
        description=(
            "Image Analyst. Given a persona image, generates a natural language "
            "description that captures the visual elements, composition, lighting, and mood. "
            "Output is plain text (3-5 sentences) for storage in the Sinergia library."
        ),
        instruction=cfg["instruction"],
        tools=[],  # Pure reasoning agent — no tool calls needed
        # before_model_callback=safety_guard_before_model,
        # after_model_callback=safety_guard_after_model,
    )
