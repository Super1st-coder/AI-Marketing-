export const currencyMapping: Record<string, CurrencyInfo> = {
  ...currencyByCode,
  xxx: unknownCurrency,
};

for (const currency of Object.values(currencyByCode)) {
  if (!currencyMapping[currency.sign]) {
    currencyMapping[currency.sign] = currency;
  }
}

export function getCurrencyInfo(currencyName: string | null | undefined) {
  if (currencyName && currencyName in currencyMapping) {
    return currencyMapping[currencyName];
  }

  return unknownCurrency;
}
